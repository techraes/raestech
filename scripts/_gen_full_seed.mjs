import fs from "node:fs";

// Regenerates supabase/migrations/00027_full_catalog_seed.sql from the client
// catalog seed (src/data/catalog_seed.json), mapping to the LIVE schema:
//   - products has category_id (nullable), no `category` column; status enum.
//   - product_variants enforces `listed_price <= buy_now_price OR buy_now_price=0`,
//     so buy_now_price is stored = listed_price (it is not read by the order /
//     instalment RPCs, which price from listed_price + settings).
//   - `condition` is the enum product_condition (box_pack|used|refurbished).
// Idempotent: emits ON CONFLICT DO NOTHING.

const seed = JSON.parse(fs.readFileSync("src/data/catalog_seed.json", "utf8"));

const q = (s) => s.replace(/'/g, "''");
const arr = (a) => `ARRAY[${(a || []).map((x) => `'${q(String(x))}'`).join(",")}]::text[]`;

const brandByLower = {};
for (const b of seed.brands || []) {
  brandByLower[String(b.name).toLowerCase()] = b.slug;
  brandByLower[String(b.slug).toLowerCase()] = b.slug;
}
const slugify = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const lines = [];
lines.push("-- Generated by scripts/_gen_full_seed.mjs from src/data/catalog_seed.json.");
lines.push("-- Idempotent: ON CONFLICT DO NOTHING. buy_now_price stored = listed_price to");
lines.push("-- satisfy product_variants check (listed_price <= buy_now_price OR buy_now_price=0);");
lines.push("-- buy_now_price is not read by the order/instalment RPCs.");
lines.push("");

// Brands
for (const b of seed.brands || []) {
  lines.push(`insert into brands (name, slug) values ('${q(b.name)}', '${q(b.slug)}') on conflict (slug) do nothing;`);
}
lines.push("");

// Products + variants
for (const p of seed.products || []) {
  const brandSlug = brandByLower[String(p.brand).toLowerCase()] || slugify(p.brand);
  const desc = q(String(p.description || "").slice(0, 2000));
  const name = q(p.name);
  const model = q(p.model || p.name || "");
  const slug = q(p.slug);
  const featured = p.featured ? "true" : "false";
  const newArr = p.new_arrival ? "true" : "false";
  const best = p.bestseller ? "true" : "false";
  lines.push(`insert into products (slug, brand_id, category_id, name, model, description, status, featured, new_arrival, bestseller)`);
  lines.push(`  select '${slug}', id, null, '${name}', '${model}', '${desc}', 'active', ${featured}, ${newArr}, ${best} from brands where slug = '${brandSlug}'`);
  lines.push(`  on conflict (slug) do nothing;`);

  for (const v of p.variants || []) {
    const listed = Number(v.listedPrice) || 0;
    const instTotal = Number(v.instalmentTotal) || listed;
    const stock = Number(v.stock) || 0;
    const reqVer = v.requiresVerification ? "true" : "false";
    const storage = q(v.storage || "");
    const ram = q(v.ram || "");
    const display = q(v.display || "");
    const chipset = q(v.chipset || "");
    const rear = q(v.rear_camera || "");
    const front = q(v.front_camera || "");
    const battery = q(v.battery || "");
    const network = q(v.network || "");
    const pta = q(v.pta_status || "");
    let condValue = "used";
    const condRaw = String(v.condition || "").toLowerCase();
    if (/new.*?box|box.*?pack|sealed/.test(condRaw)) condValue = "box_pack";
    else if (/refurb/.test(condRaw)) condValue = "refurbished";
    lines.push(
      `insert into product_variants (product_id, sku, storage, ram, colors, display, chipset, rear_camera, front_camera, battery, network, pta_status, condition, listed_price, buy_now_price, instalment_total, stock, requires_verification, is_active)`
    );
    lines.push(
      `  select id, '${q(v.sku)}', '${storage}', '${ram}', ${arr(v.colors)}, '${display}', '${chipset}', '${rear}', '${front}', '${battery}', '${network}', '${pta}', '${condValue}', ${listed}, ${listed}, ${instTotal}, ${stock}, ${reqVer}, true from products where slug = '${slug}'`
    );
    lines.push(`  on conflict (sku) do nothing;`);
  }
}

fs.writeFileSync("supabase/migrations/00027_full_catalog_seed.sql", lines.join("\n") + "\n");
console.log("wrote supabase/migrations/00027_full_catalog_seed.sql", lines.length, "lines");
