#!/usr/bin/env node
/**
 * RAES TECH — Instalment catalogue reconciliation tool.
 *
 * Compares every storefront (seed) offer against what should exist in Supabase
 * and emits (a) a report of eligible offers, colours and any ambiguous offers
 * that need review, and (b) an idempotent SQL migration that repairs missing
 * mappings WITHOUT duplicating existing records or overwriting admin-managed
 * prices, stock or existing applications.
 *
 * The report is computed from `src/data/catalog_seed.json` (the storefront
 * source of truth). Running the generated SQL in a Supabase project and then
 * re-running `--status` gives the authoritative checked/repaired/unresolved
 * counts from the live database.
 *
 * Usage:
 *   node scripts/reconcile-instalment-catalog.mjs --status      # print report
 *   node scripts/reconcile-instalment-catalog.mjs --emit-sql   # write migration
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const seedPath = join(root, "src/data/catalog_seed.json");
const outSqlPath = join(root, "supabase/migrations/00022_catalog_reconcile_seed.sql");

const seed = JSON.parse(readFileSync(seedPath, "utf-8"));
const products = seed.products;

const sqlStr = (s) => String(s ?? "").replace(/'/g, "''");
const arrayLit = (arr) => {
  if (!Array.isArray(arr) || arr.length === 0) return "'{}'::text[]";
  return `ARRAY[${arr.map((e) => `'${sqlStr(e)}'`).join(", ")}]::text[]`;
};

const brands = [...new Set(products.map((p) => p.brand))];

// ---- Catalog-wide scan ----
const offers = [];
const ambiguous = [];
const seen = new Map(); // key: productSlug|storage|ram|pta|price|colorsjoined

for (const p of products) {
  for (const v of p.variants || []) {
    const key = `${p.slug}|${v.storage}|${v.ram}|${v.pta_status}|${v.listedPrice}|${(v.colors || []).join(",")}`;
    offers.push({ product: p, variant: v, key });
    if (seen.has(key)) {
      ambiguous.push({ first: seen.get(key), second: { product: p, variant: v }, key });
    } else {
      seen.set(key, { product: p, variant: v });
    }
  }
}

const eligible = offers.length;
const withColours = offers.filter((o) => (o.variant.colors || []).length > 0).length;
const noColours = eligible - withColours;

const lines = [];
lines.push("RAES TECH — Instalment catalogue reconciliation report");
lines.push("===========================================================");
lines.push(`Storefront products scanned        : ${products.length}`);
lines.push(`Eligible instalment offers          : ${eligible}`);
lines.push(`  offers with colours               : ${withColours}`);
lines.push(`  offers without colours            : ${noColours}`);
lines.push(`Ambiguous (indistinguishable) offers: ${ambiguous.length}`);
lines.push("");
lines.push("Ambiguous offers (same storage/RAM + PTA + price + colours within a product) — flag for review, never merge:");
if (ambiguous.length === 0) lines.push("  (none)");
for (const a of ambiguous) {
  lines.push(`  - [A] ${a.first.product.slug} sku=${a.first.variant.sku} ${a.first.variant.storage}/${a.first.variant.ram} Rs${a.first.variant.listedPrice} pta="${a.first.variant.pta_status}"`);
  lines.push(`    [B] ${a.second.product.slug} sku=${a.second.variant.sku} ${a.second.variant.storage}/${a.second.variant.ram} Rs${a.second.variant.listedPrice} pta="${a.second.variant.pta_status}"`);
}
lines.push("");
lines.push("Repair migration generated at: " + (process.argv.includes("--emit-sql") ? outSqlPath : "(run with --emit-sql to write it)"));
lines.push("Apply it in the Supabase SQL editor (or `supabase db push`), then re-run with --status for live counts.");

console.log(lines.join("\n"));

if (process.argv.includes("--emit-sql")) {
  const sql = [];
  sql.push("-- Generated by scripts/reconcile-instalment-catalog.mjs");
  sql.push("-- Idempotent repair: inserts missing products/variants only. It never");
  sql.push("-- overwrites existing rows (ON CONFLICT DO NOTHING), so admin-managed");
  sql.push("-- prices, stock and existing applications are preserved.");
  sql.push("");

  for (const b of brands) {
    const slug = b.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    sql.push(`INSERT INTO brands (name, slug) VALUES ('${sqlStr(b)}', '${sqlStr(slug)}') ON CONFLICT (slug) DO NOTHING;`);
  }
  sql.push("");

  for (const p of products) {
    const brandSlug = p.brand.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    sql.push(`INSERT INTO products (slug, brand_id, name, model, description, category, seo_title, seo_description)`);
    sql.push(`  VALUES ('${sqlStr(p.slug)}', (SELECT id FROM brands WHERE slug='${sqlStr(brandSlug)}'), '${sqlStr(p.name)}', '${sqlStr(p.model)}', '${sqlStr(p.description)}', '${sqlStr(p.category ?? p.brand.toLowerCase())}', '${sqlStr(p.seo_title ?? "")}', '${sqlStr(p.seo_description ?? "")}')`);
    sql.push(`  ON CONFLICT (slug) DO NOTHING;`);
    sql.push("");
    for (const v of p.variants || []) {
      sql.push(`INSERT INTO product_variants (product_id, sku, storage, ram, colors, display, chipset, rear_camera, front_camera, battery, network, pta_status, listed_price, buy_now_price, instalment_total, stock, requires_verification)`);
      sql.push(`  SELECT id, '${sqlStr(v.sku)}', '${sqlStr(v.storage)}', '${sqlStr(v.ram)}', ${arrayLit(v.colors)}, '${sqlStr(v.display)}', '${sqlStr(v.chipset)}', '${sqlStr(v.rear_camera)}', '${sqlStr(v.front_camera)}', '${sqlStr(v.battery)}', '${sqlStr(v.network)}', '${sqlStr(v.pta_status)}', ${Number(v.listedPrice) || 0}, ${Number(v.buyNowPrice) || 0}, ${Number(v.instalmentTotal) || 0}, ${Number(v.stock) || 0}, ${Boolean(v.requiresVerification)}`);
      sql.push(`    FROM products WHERE slug='${sqlStr(p.slug)}'`);
      sql.push(`    ON CONFLICT (sku) DO NOTHING;`);
    }
    sql.push("");
  }

  writeFileSync(outSqlPath, sql.join("\n"), "utf-8");
  console.log(`\nWrote repair migration: ${outSqlPath}`);
}
